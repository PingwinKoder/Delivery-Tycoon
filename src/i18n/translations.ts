export function getWeekdayName(
  lang: SupportedLanguage,
  weekdayIndex: number,
  short = false
): string {
  const table = short ? WEEKDAYS_SHORT[lang] ?? WEEKDAYS_SHORT.pl : WEEKDAYS_FULL[lang] ?? WEEKDAYS_FULL.pl;
  return table[((weekdayIndex % 7) + 7) % 7] ?? '';
}

export function getMonthName(
  lang: SupportedLanguage,
  monthIndex: number,
  short = false
): string {
  const table = short ? MONTHS_SHORT[lang] ?? MONTHS_SHORT.pl : MONTHS_FULL[lang] ?? MONTHS_FULL.pl;
  return table[((monthIndex % 12) + 12) % 12] ?? '';
}

